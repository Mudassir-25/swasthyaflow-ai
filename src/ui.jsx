import React, { useEffect, useState } from 'react';
import { api } from './api.js';
import { useApp } from './store.jsx';

export const RC = { CRITICAL: 'crit', HIGH: 'high', MODERATE: 'mod', LOW: 'low' };
export const Chip = ({ risk }) => <span className={`chip ${RC[risk]}`}>{risk}</span>;
export const nf = (n) => Math.round(n).toLocaleString('en-IN');
export const dayText = (d) => `${d} day${d === 1 ? '' : 's'}`;

export function Card({ title, right, children, className = '', pad = true }) {
  return (
    <section className={`card ${className}`}>
      {(title || right) && <header className="card-h"><h3>{title}</h3>{right}</header>}
      <div className={pad ? 'card-b' : ''}>{children}</div>
    </section>
  );
}
export function Kpi({ label, value, sub, tone }) {
  return <div className={`kpi ${tone || ''}`}><div className="kpi-v">{value}</div><div className="kpi-l">{label}</div>{sub && <div className="kpi-s">{sub}</div>}</div>;
}
export function Runway({ exactDays, risk }) {
  const max = 14, pct = Math.min(100, (Math.max(0, exactDays) / max) * 100);
  return (
    <div className="runway" role="img" aria-label={`${exactDays.toFixed(1)} days of stock remaining`}>
      <div className="runway-track"><div className={`runway-fill ${RC[risk]}`} style={{ width: pct + '%' }} /><div className="runway-safe" style={{ left: (3.5 / max) * 100 + '%' }} /></div>
      <div className="runway-scale"><span>0</span><span style={{ marginLeft: `${(3.5 / max) * 100 - 3}%` }}>3.5 d critical line</span><span style={{ marginLeft: 'auto' }}>14+ days</span></div>
    </div>
  );
}
export function SourceBadge({ r }) {
  if (!r) return null;
  if (r.source === 'gemini') return <span className="src live" title="Generated by Google Gemini through the server-side API">Gemini · {r.model}</span>;
  return <span className="src demo" title={r.geminiError || 'Deterministic local logic'}>DEMO response · not Gemini{r.geminiError ? ' (Gemini call failed)' : ''}</span>;
}
export function useTranslated(items, lang) {
  const key = JSON.stringify(items) + lang;
  const [st, setSt] = useState({});
  useEffect(() => {
    if (lang === 'en' || !items.length) { setSt({}); return; }
    let live = true; setSt({});
    api.translate(items, lang).then((r) => live && setSt({ out: r.translations, translated: r.translated, source: r.source, model: r.model, geminiError: r.geminiError })).catch(() => live && setSt({ error: true }));
    return () => { live = false; };
  }, [key]);
  return st;
}
export const advText = (r) => `${r.medName} stock at ${r.phcName} may fall below safety levels in ${r.days} days.`;
export function Advisories({ recs }) {
  const { lang } = useApp();
  const items = recs.map((r) => ({ text: advText(r), template: { phc: r.phcName, medicine: r.medName, days: r.days } }));
  const t = useTranslated(items, lang);
  return (
    <div className="adv-list">
      {items.map((it, i) => (
        <div className="adv" key={i}>
          <div>{it.text}</div>
          {lang !== 'en' && <div className="adv-t" lang={lang}>{t.error ? 'Translation unavailable' : t.out ? t.out[i] : 'Translating…'}</div>}
        </div>
      ))}
      {lang !== 'en' && t.source && <div className="adv-src"><SourceBadge r={t} /></div>}
    </div>
  );
}
